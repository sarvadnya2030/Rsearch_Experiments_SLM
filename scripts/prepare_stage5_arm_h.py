"""
Stage 5, Arm H (NEW) — external teacher, Program-of-Thought format, sourced
from NVIDIA's OpenMathInstruct-1 rather than generated by this project's own
teacher (GPT-OSS-20B).

Motivation (see research-plan.md Stage 5, 2026-09-09 update): the baseline
failure taxonomy shows misread_semantics (55.5% of errors) dominating over
arithmetic_slip (10%) — the model's real weakness is building a correct
situation model of the problem, not computing. Code with explicitly named
variables forces exactly the quantity-binding step that's currently failing
(PAL, Gao et al. 2022; PaD, Zhu et al. NAACL 2024).

OpenMathInstruct-1's GSM8K-tagged rows use our exact GSM8K train question
text (verified: 500/500 sampled rows matched verbatim) and are already
correctness-verified (`is_correct`) — no new teacher generation or
verification pass needed, just matching + light reformatting.

Reformatting: OpenMathInstruct's generated_solution always ends with
"...\\boxed{N}..." embedded in a sentence — a format our extraction
pipeline (src/evaluation/answer_extraction.py) doesn't parse. Rather than
touch the actual code/reasoning content (the experimental variable), we
append our standard "The answer is N." after the existing text, so every
arm is extracted identically and the comparison isolates "code vs prose,"
not "different answer-ending phrasing."

Usage:
    python scripts/prepare_stage5_arm_h.py --out results/exp05_arm_h/arm_h_openmath_code.jsonl \
        --max-rows-scanned 300000
"""

import argparse
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from datasets import load_dataset  # noqa: E402
from src.data.gsm8k import extract_reference_answer  # noqa: E402
from src.evaluation.answer_extraction import is_correct  # noqa: E402
from src.utils.logging import get_logger  # noqa: E402

logger = get_logger("prepare_stage5_arm_h")

BOXED_PATTERN = re.compile(r"\\boxed\{([\-\$]?[\d,]*\.?\d+)\}")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True)
    ap.add_argument("--max-rows-scanned", type=int, default=300000,
                     help="Cap on OpenMathInstruct-1 rows streamed (it has ~1.8M total, most of it MATH not GSM8K)")
    args = ap.parse_args()

    logger.info("Loading our own GSM8K train split to build the question->example_id lookup")
    our_train = load_dataset("openai/gsm8k", "main", split="train")
    question_to_id = {}
    reference_answers = {}
    for idx, row in enumerate(our_train):
        q = row["question"].strip()
        question_to_id[q] = idx
        reference_answers[idx] = extract_reference_answer(row["answer"])
    logger.info(f"{len(question_to_id)} train questions loaded")

    logger.info(f"Streaming OpenMathInstruct-1, scanning up to {args.max_rows_scanned} rows")
    ds = load_dataset("nvidia/OpenMathInstruct-1", split="train", streaming=True)

    kept_by_id = {}
    n_scanned = 0
    n_gsm8k_seen = 0
    n_boxed_missing = 0
    n_verify_failed = 0

    for row in ds:
        n_scanned += 1
        if n_scanned > args.max_rows_scanned:
            break
        if row["dataset"] != "gsm8k" or not row["is_correct"]:
            continue
        n_gsm8k_seen += 1

        q = row["question"].strip()
        example_id = question_to_id.get(q)
        if example_id is None or example_id in kept_by_id:
            continue  # not one of ours, or we already kept a solution for this question

        boxed_match = BOXED_PATTERN.search(row["generated_solution"])
        if not boxed_match:
            n_boxed_missing += 1
            continue

        reference_answer = reference_answers[example_id]
        boxed_answer = boxed_match.group(1)
        if not is_correct(boxed_answer, reference_answer):
            n_verify_failed += 1
            logger.warning(f"example {example_id}: boxed answer {boxed_answer!r} != reference {reference_answer!r}")
            continue

        reasoning_trace = row["generated_solution"].strip() + f" The answer is {reference_answer}."
        kept_by_id[example_id] = {
            "example_id": example_id,
            "question": row["question"],
            "reference_answer": reference_answer,
            "reasoning_trace": reasoning_trace,
            "arm": "H_openmath_pot",
            "source": "openmathinstruct1_gsm8k_code",
        }

    out_path = Path(args.out)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    with open(out_path, "w") as f:
        for example_id in sorted(kept_by_id):
            f.write(json.dumps(kept_by_id[example_id]) + "\n")

    logger.info(
        f"Scanned {n_scanned} rows ({n_gsm8k_seen} gsm8k-tagged+correct). "
        f"Matched+kept {len(kept_by_id)}/{len(question_to_id)} of our train questions "
        f"({len(kept_by_id)/len(question_to_id):.1%} coverage). "
        f"Skipped: {n_boxed_missing} missing \\boxed{{}}, {n_verify_failed} failed re-verification."
    )
    logger.info(f"Written to {out_path}")


if __name__ == "__main__":
    main()
